// A parchment poster laid over one of the baked wall frames.
function PosterOverlay({ lock, geometry, position, rotation, brightness, fontReady, solved, handlers }) {
  // Where the baked frame sits in the group's space.
  const box = useMemo(() => {
    if (!geometry.boundingBox) geometry.computeBoundingBox();
    const matrix = new THREE.Matrix4().compose(
      new THREE.Vector3(...position),
      new THREE.Quaternion().setFromEuler(new THREE.Euler(...rotation)),
      new THREE.Vector3(1, 1, 1)
    );
    return geometry.boundingBox.clone().applyMatrix4(matrix);
  }, [geometry, position, rotation]);

  const size = box.getSize(new THREE.Vector3());
  const center = box.getCenter(new THREE.Vector3());
  const width = size.x * 0.8;
  const height = size.y * 0.8;

  const texture = useMemo(
    () => drawLockPoster(lock, height / width, solved),
    // Redraw when the font loads or the lock opens.
    // eslint-disable-next-line react-hooks/exhaustive-deps
    [lock.key, width, height, fontReady, solved]
  );

  useEffect(() => () => texture.dispose(), [texture]);

  return (
    <mesh position={[center.x, center.y, box.max.z + 0.02]} {...handlers}>
      <planeGeometry args={[width, height]} />
      <meshBasicMaterial map={texture} toneMapped={false} color={[brightness, brightness, brightness]} />
    </mesh>
  );
}

