function wrapText(ctx, text, maxWidth) {
  const words = text.split(" ");
  const lines = [];
  let line = "";
  for (const word of words) {
    const test = line ? `${line} ${word}` : word;
    if (ctx.measureText(test).width > maxWidth && line) {
      lines.push(line);
      line = word;
    } else {
      line = test;
    }
  }
  if (line) lines.push(line);
  return lines;
}

function parchment(ctx, W, H) {
  const bg = ctx.createRadialGradient(W / 2, H / 2, W * 0.1, W / 2, H / 2, W * 0.9);
  bg.addColorStop(0, "#efe2c2");
  bg.addColorStop(0.7, "#d6c095");
  bg.addColorStop(1, "#9a7b4f");
  ctx.fillStyle = bg;
  ctx.fillRect(0, 0, W, H);
}

function drawKeyhole(ctx, x, y, s, color) {
  ctx.save();
  ctx.fillStyle = color;
  ctx.beginPath();
  ctx.arc(x, y, s * 0.32, 0, Math.PI * 2);
  ctx.fill();
  ctx.beginPath();
  ctx.moveTo(x - s * 0.16, y + s * 0.1);
  ctx.lineTo(x + s * 0.16, y + s * 0.1);
  ctx.lineTo(x + s * 0.26, y + s * 0.75);
  ctx.lineTo(x - s * 0.26, y + s * 0.75);
  ctx.closePath();
  ctx.fill();
  ctx.restore();
}

function drawSeal(ctx, x, y, r) {
  ctx.save();
  ctx.translate(x, y);
  ctx.rotate(-0.18);
  const g = ctx.createRadialGradient(-r * 0.3, -r * 0.3, r * 0.1, 0, 0, r);
  g.addColorStop(0, "#3f9b55");
  g.addColorStop(1, "#14401f");
  ctx.fillStyle = g;
  ctx.beginPath();
  ctx.arc(0, 0, r, 0, Math.PI * 2);
  ctx.fill();
  ctx.strokeStyle = "rgba(255,255,255,0.35)";
  ctx.lineWidth = r * 0.06;
  ctx.beginPath();
  ctx.arc(0, 0, r * 0.78, 0, Math.PI * 2);
  ctx.stroke();
  ctx.fillStyle = "#eaf7e6";
  ctx.textAlign = "center";
  ctx.textBaseline = "middle";
  ctx.font = `${Math.round(r * 0.34)}px ${TITLE_FONT}`;
  ctx.fillText("OPEN", 0, 0);
  ctx.restore();
}

// Draws one lock frame: numeral, title, the clue, and a seal once it is open.
function drawLockPoster(lock, aspect, solved) {
  const W = 768;
  const H = Math.round(W * aspect);
  const canvas = document.createElement("canvas");
  canvas.width = W;
  canvas.height = H;
  const ctx = canvas.getContext("2d");
  parchment(ctx, W, H);

  ctx.strokeStyle = "#3b2414";
  ctx.lineWidth = 7;
  ctx.strokeRect(24, 24, W - 48, H - 48);
  ctx.lineWidth = 2;
  ctx.strokeRect(40, 40, W - 80, H - 80);

  const ink = "#24150a";
  ctx.textAlign = "center";
  ctx.textBaseline = "middle";
  ctx.fillStyle = "#7a1d10";
  ctx.font = `${Math.round(W * 0.06)}px ${TITLE_FONT}`;
  ctx.fillText(`Lock ${lock.numeral}`, W / 2, H * 0.1);

  ctx.fillStyle = ink;
  ctx.font = `${Math.round(W * 0.07)}px ${TITLE_FONT}`;
  let y = H * 0.2;
  for (const line of wrapText(ctx, lock.title, W * 0.8)) {
    ctx.fillText(line, W / 2, y);
    y += W * 0.085;
  }

  drawKeyhole(ctx, W / 2, y + W * 0.05, W * 0.1, solved ? "rgba(36,21,10,0.25)" : "#24150a");
  y += W * 0.22;

  const mono = lock.id === "f3" || lock.id === "f4";
  ctx.font = mono ? `${Math.round(W * 0.06)}px "Courier New", monospace` : `${Math.round(W * 0.068)}px ${TITLE_FONT}`;
  for (const line of lock.wall) {
    ctx.fillText(line, W / 2, y);
    y += W * 0.09;
  }

  ctx.font = `italic ${Math.round(W * 0.034)}px ${TITLE_FONT}`;
  ctx.fillStyle = "#4a3020";
  ctx.fillText(solved ? "this lock is open" : "touch to try the lock", W / 2, H - W * 0.09);

  if (solved) drawSeal(ctx, W * 0.76, H - W * 0.25, W * 0.13);

  const texture = new THREE.CanvasTexture(canvas);
  texture.colorSpace = THREE.SRGBColorSpace;
  texture.anisotropy = 8;
  return texture;
}

